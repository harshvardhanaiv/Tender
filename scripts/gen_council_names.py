#!/usr/bin/env python3
"""Writes etenders_scraper/council_names.py: for each council published under several spellings, the one name its awards go under.

Reads contract_awards (read-only) and groups names by the same key etenders_scraper.awards.council_core uses. A group is listed only
when two or more different spellings exist and one of them carries a council marker. Successor authorities (a county council and the
unitary council that replaced it) are not merged: see SEPARATE below.

    python scripts/gen_council_names.py            # dry: prints the table
    python scripts/gen_council_names.py --write    # writes etenders_scraper/council_names.py
"""
from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from etenders_scraper.awards import council_core  # noqa: E402
from tender_app.db import get_db_connection  # noqa: E402

# Two different legal bodies that share a core: the old county council and the council that replaced it, and a non-council.
SEPARATE = {"north yorkshire", "buckinghamshire", "dorset", "somerset", "cumbria", "northamptonshire", "british", "kent", "bedford", "central bedfordshire"}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--live", action="store_true", help="read the production database (read-only session) instead of the dev one")
    args = ap.parse_args()
    if args.live:
        import psycopg2
        conn = psycopg2.connect(host="62.171.162.135", port=5440, user="postgres", password="root", dbname="postgres")
    else:
        conn = get_db_connection()
    cur = conn.cursor()
    cur.execute("SET default_transaction_read_only = on;")
    cur.execute("SELECT authority_name, COUNT(*) FROM contract_awards WHERE authority_name ~* 'council|borough|city of|mbc' GROUP BY 1")
    groups: dict[str, list[tuple[str, int]]] = defaultdict(list)
    for name, n in cur.fetchall():
        core = council_core(name)
        if core and core not in SEPARATE:
            groups[core].append((" ".join(name.split()), n))
    conn.rollback()
    table = {}
    for core, spellings in groups.items():
        merged: dict[str, int] = defaultdict(int)
        for nm, n in spellings:
            merged[nm] += n
        if len(merged) < 2:
            continue
        # the most used spelling that is not shouted and not an abbreviation
        pref = sorted(merged.items(), key=lambda kv: (kv[0].isupper() or kv[0].lower().endswith("mbc") or kv[0].startswith("."), -kv[1]))
        table[core] = pref[0][0]
    for core, name in sorted(table.items()):
        print(f"{core!r}: {name!r}")
    print(len(table), "councils")
    if args.write:
        lines = ['"""Generated by scripts/gen_council_names.py: council -> the one name its awards are listed under. Edit by hand if a name is wrong."""',
                 "COUNCIL_CANON = {"]
        lines += [f"    {core!r}: {name!r}," for core, name in sorted(table.items())]
        lines.append("}")
        (ROOT / "etenders_scraper" / "council_names.py").write_text("\n".join(lines) + "\n", encoding="utf8")
        print("written")


if __name__ == "__main__":
    main()
